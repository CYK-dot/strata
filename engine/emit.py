"""Write the two views (CMake, C) plus the manifest."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .. import __version__
from .components import Component
from .preset import Preset
from .resolve import Resolved
from .schema import Schema

FEATURE_PREFIX = "STRATA_FEATURE_"
CONFIG_PREFIX = "STRATA_CONFIG_"


def write(
    out_dir: str | Path,
    schema: Schema,
    preset: Preset,
    components: list[Component],
    resolved: list[Resolved],
    inputs: dict[str, str],
) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    banner = (
        f"generated by strata {__version__} | preset={preset.name} | "
        f"inputs {_inputs_digest(inputs)}"
    )
    written: list[Path] = []

    written.append(_write_features_cmake(out, banner, resolved))
    for layer, items in sorted(_by_layer(resolved).items()):
        written.append(_write_layer_header(out, layer, banner, items))
    written.append(_write_config_header(out, banner, preset))
    written.append(_write_config_cmake(out, banner, preset))
    written.append(_write_manifest(out, preset, components, resolved, inputs, schema))
    return written


# -- rendering -----------------------------------------------------------------


def _cmake_value(value: Any) -> str:
    if type(value) is bool:
        return "ON" if value else "OFF"
    if type(value) is str:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return repr(value)


def _c_value(value: Any) -> str:
    if type(value) is bool:
        return "1" if value else "0"
    if type(value) is float:
        return f"{value!r}f"
    if type(value) is str:
        return _c_string(value)
    return repr(value)


def _c_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _macro(prefix: str, identifier: str) -> str:
    return prefix + identifier.upper().replace(".", "_")


def _write_features_cmake(out: Path, banner: str, resolved: list[Resolved]) -> Path:
    lines = [
        f"# {banner}",
        "# Do not edit. Regenerate with: python -m strata generate ...",
        "",
    ]
    for item in sorted(resolved, key=lambda r: r.declaration.name):
        lines.append(
            f"set({FEATURE_PREFIX}{item.declaration.name} {_cmake_value(item.value)})"
        )
    path = out / "strata_features.cmake"
    _write(path, "\n".join(lines) + "\n")
    return path


def _write_layer_header(out: Path, layer: str, banner: str, items: list[Resolved]) -> Path:
    guard = f"STRATA_FEATURES_{layer.upper()}_H"
    lines = [
        f"/* {banner}",
        " * Do not edit. Regenerate with: python -m strata generate ...",
        " */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
    ]
    for item in sorted(items, key=lambda r: r.declaration.name):
        lines.append(
            f"#define {_macro(FEATURE_PREFIX, item.declaration.name)} "
            f"{_c_value(item.value)}"
        )
    lines.extend(["", f"#endif /* {guard} */"])
    path = out / layer / "strata_features.h"
    _write(path, "\n".join(lines) + "\n")
    return path


def _write_config_header(out: Path, banner: str, preset: Preset) -> Path:
    lines = [
        f"/* {banner}",
        " * Raw problem-domain facts for this preset. Do not use them directly",
        " * in solution-domain code; prefer the features of your own layer.",
        " */",
        "#ifndef STRATA_CONFIG_H",
        "#define STRATA_CONFIG_H",
        "",
    ]
    for identifier in sorted(preset.values):
        lines.append(f"#define {_macro(CONFIG_PREFIX, identifier)} {_c_value(preset.values[identifier])}")
    lines.extend(["", "#endif /* STRATA_CONFIG_H */"])
    path = out / "config" / "strata_config.h"
    _write(path, "\n".join(lines) + "\n")
    return path


def _write_config_cmake(out: Path, banner: str, preset: Preset) -> Path:
    lines = [f"# {banner}", ""]
    for identifier in sorted(preset.values):
        lines.append(f"set({CONFIG_PREFIX}{identifier} {_cmake_value(preset.values[identifier])})")
    path = out / "config" / "strata_config.cmake"
    _write(path, "\n".join(lines) + "\n")
    return path


def _write_manifest(
    out: Path,
    preset: Preset,
    components: list[Component],
    resolved: list[Resolved],
    inputs: dict[str, str],
    schema: Schema,
) -> Path:
    features = {}
    for item in resolved:
        features[item.declaration.name] = {
            "value": item.value,
            "type": item.declaration.type,
            "layer": item.declaration.layer,
            "owner": item.declaration.component,
            "by": item.reads,
        }
    manifest = {
        "engine": f"strata {__version__}",
        "preset": preset.name,
        "inputs": inputs,
        "features": features,
        "components": {
            component.id: {
                "layer": component.layer,
                "features": sorted(decl.name for decl in component.declarations),
            }
            for component in components
        },
        "config": preset.values,
        "schema": {identifier: schema.dimensions[identifier].type for identifier in schema.ids()},
    }
    path = out / "strata_manifest.json"
    _write(path, json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
    return path


def _by_layer(resolved: list[Resolved]) -> dict[str, list[Resolved]]:
    grouped: dict[str, list[Resolved]] = {}
    for item in resolved:
        grouped.setdefault(item.declaration.layer, []).append(item)
    return grouped


def _inputs_digest(inputs: dict[str, str]) -> str:
    import hashlib

    digest = hashlib.sha256()
    for name in sorted(inputs):
        digest.update(f"{name}:{inputs[name]}\n".encode("utf-8"))
    return "sha256:" + digest.hexdigest()[:16]


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
